using System.Globalization;
using KetPsi.EntityFrameworkCore.Generator.Discovery;
using KetPsi.EntityFrameworkCore.Generator.Model;

namespace KetPsi.EntityFrameworkCore.Generator.Emit;

/// <summary>
/// Emits the interceptors: one method per intercepted call, which appends the operator to the KetPsi query or runs
/// it, and calls the original method when the source is not an entity query.
/// </summary>
internal static class InterceptorEmitter
{
    public const string HintName = "KetPsi.Interceptors.g.cs";

    private const string SqlQuery = "global::KetPsi.EntityFrameworkCore.Infrastructure.SqlQuery";
    private const string SqlProjection = "global::KetPsi.EntityFrameworkCore.Infrastructure.SqlProjection";
    private const string SqlGrouping = "global::KetPsi.EntityFrameworkCore.Infrastructure.SqlGrouping";
    private const string GroupValue = "global::KetPsi.EntityFrameworkCore.Infrastructure.GroupValue";
    private const string ProjectionReader = "global::KetPsi.EntityFrameworkCore.Infrastructure.ProjectionReader";
    private const string Queryable = "global::System.Linq.IQueryable";
    private const string ReaderHelper = "Reader";
    private const string AggregateFunction = "global::KetPsi.EntityFrameworkCore.Sql.AggregateFunction";
    private const string AggregateValueType = "global::KetPsi.EntityFrameworkCore.Sql.AggregateValueType";
    private const string CapturedValues = "global::KetPsi.EntityFrameworkCore.Infrastructure.CapturedValues";
    private const string PredicateTemplate = "global::KetPsi.EntityFrameworkCore.Infrastructure.Templates.PredicateTemplate";
    private const string Enumerable = "global::System.Linq.Enumerable";
    private const string ExpressionType = "global::System.Linq.Expressions.Expression<";
    private const string NoValues = "global::System.Array.Empty<object?>()";
    private const string AsyncSuffix = "Async";
    private const string DynamicDependency = "global::System.Diagnostics.CodeAnalysis.DynamicDependency";
    private const string DynamicallyAccessedMemberTypes = "global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes";

    /// <summary>Whether the site has everything its interceptor needs.</summary>
    public static bool CanIntercept(CallSite site)
        => site is { Interception: not null, Signature: not null, Operator: { } kind }
            && (site.Group is not null || CanInterceptEntityOperator(site, kind));

    private static bool CanInterceptEntityOperator(CallSite site, OperatorKind kind)
        => (!TakesPredicate(site) || site.Predicate is not null)
            && (!IsOrdering(kind) || site.OrderProperty is not null)
            && (kind is not (OperatorKind.Include or OperatorKind.ThenInclude) || site.Include is not null)
            && (kind != OperatorKind.Select || site.Projection is not null)
            && (!IsAggregate(kind) || site.Aggregate is not null);

    public static string Emit(IReadOnlyList<CallSite> sites)
    {
        var writer = new CodeWriter()
            .Line("// <auto-generated/>")
            .Line("#nullable enable")
            .Line();

        WriteAttribute(writer);

        writer
            .Line()
            .Open("namespace " + QueryInterceptorGenerator.GeneratedNamespace)
            .Line("[global::System.CodeDom.Compiler.GeneratedCode(\"KetPsi.EntityFrameworkCore.Generator\", null)]")
            .Open("file static class KetPsiInterceptors");

        for (var i = 0; i < sites.Count; i++)
        {
            if (i > 0)
            {
                writer.Line();
            }

            WriteInterceptor(writer, sites[i], i);
        }

        if (sites.Any(static s => s.Operator == OperatorKind.Select || s.Group is not null))
        {
            // Converts a reader lambda to its delegate type, inferring the projected type, which can be anonymous.
            writer
                .Line()
                .Line($"private static {ProjectionReader}<T> {ReaderHelper}<T>({ProjectionReader}<T> reader) => reader;");
        }

        return writer.Close().Close().ToString();
    }

    // The compiler recognizes the attribute by name; each generating assembly declares its own file-local copy.
    private static void WriteAttribute(CodeWriter writer)
        => writer
            .Open("namespace System.Runtime.CompilerServices")
            .Line("[global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]")
            .Open("file sealed class InterceptsLocationAttribute : global::System.Attribute")
            .Open("public InterceptsLocationAttribute(int version, string data)")
            .Line("_ = version;")
            .Line("_ = data;")
            .Close()
            .Close()
            .Close();

    private static void WriteInterceptor(CodeWriter writer, CallSite site, int index)
    {
        var signature = site.Signature!;
        var number = index.ToString(CultureInfo.InvariantCulture);
        var template = "Template" + number;
        var parameters = signature.Parameters;
        var source = parameters[0].Name;
        var arguments = string.Join(", ", parameters.Select(static p => p.Name));
        var declaration = string.Join(", ", parameters.Select(static (p, i) => (i == 0 ? "this " : "") + p.Type + " " + p.Name));
        var fallback = $"{signature.ContainingType}.{signature.Name}({arguments})";

        if (site.Predicate is not null)
        {
            writer.Line($"private static readonly {PredicateTemplate} {template} = {site.Predicate.TemplateCode};").Line();
        }

        if (site.Group?.TemplateCode is { } groupTemplate)
        {
            writer.Line($"private static readonly {PredicateTemplate} {template} = {groupTemplate};").Line();
        }

        if (site.Group is { } groupCall && GroupValues(groupCall) is { Count: > 0 } groupValues)
        {
            writer.Line($"private static readonly {GroupValue}[] Values{number} = new {GroupValue}[] {{ {string.Join(", ", groupValues)} }};").Line();
        }

        writer.Line(site.Interception!);
        if (site.UsesDecimalOperators)
        {
            // The caller builds this lambda's decimal operators by reflection; keep decimal's methods for it under Native AOT.
            writer.Line($"[{DynamicDependency}({DynamicallyAccessedMemberTypes}.PublicMethods, typeof(decimal))]");
        }

        var typeParameters = signature.TypeParameters.Count == 0 ? "" : "<" + string.Join(", ", signature.TypeParameters) + ">";
        writer.Open($"public static {signature.ReturnType} {signature.Name}{number}{typeParameters}({declaration})");

        if (site.Group is { } group)
        {
            WriteGroup(writer, site, group, source, fallback, template, "Values" + number);
            return;
        }

        if (site.ProjectedFrom is not null)
        {
            WriteProjected(writer, site, source, fallback);
            return;
        }

        if (site.Operator == OperatorKind.Select)
        {
            WriteSelect(writer, site, source, fallback);
            return;
        }

        if (signature.ContainingType == Enumerable)
        {
            // Enumerable.ToList and ToArray accept any sequence; only KetPsi queries and DbSets run here.
            var query = $"global::System.Linq.IQueryable<{site.ElementType}>";
            writer
                .Open($"if ({source} is {query} query && {SqlQuery}.IsInterceptable(query))")
                .Line($"return {SqlQuery}.{site.Operator}(query);")
                .Close()
                .Line()
                .Line($"return {fallback};")
                .Close();
            return;
        }

        writer
            .Open($"if (!{SqlQuery}.IsInterceptable({source}))")
            .Line($"return {fallback};")
            .Close()
            .Line();

        if (site.Predicate is { ValuePaths.Count: > 0 })
        {
            var predicateParameter = parameters.First(static p => p.Type.StartsWith(ExpressionType, StringComparison.Ordinal)).Name;
            writer.Line($"var {PredicateTranslator.BodyVariable} = {predicateParameter}.Body;");
        }

        writer.Line("return " + Body(site, source, template) + ";").Close();
    }

    // The query is cast to the entity query it is, so its type argument can be named.
    private static void WriteSelect(CodeWriter writer, CallSite site, string source, string fallback)
    {
        var projection = site.Projection!;
        var signature = site.Signature!;
        var result = signature.TypeParameters[signature.TypeParameters.Count - 1];
        writer
            .Line($"var query = ({Queryable}<{site.ElementType}>)(object){source};")
            .Open($"if (!{SqlQuery}.IsInterceptable(query))")
            .Line($"return {fallback};")
            .Close()
            .Line();

        if (projection.CaptureCount > 0)
        {
            // Captured values are read once per query, in source order, from the lambda the caller built.
            writer.Line($"var {ProjectionTranslator.Captures} = {CapturedValues}.ReadAll({signature.Parameters[1].Name});");
        }

        writer
            .Line($"return ({Queryable}<{result}>)(object){SqlQuery}.Select(")
            .Line($"    query,")
            .Line($"    {Strings(projection.PropertyPaths)},")
            .Line($"    {Strings(projection.EntityPaths)},")
            .Line($"    {ReaderHelper}({projection.ReaderCode}));")
            .Close();
    }

    private static void WriteProjected(CodeWriter writer, CallSite site, string source, string fallback)
    {
        var parameters = site.Signature!.Parameters;
        var element = site.Signature.TypeParameters.Count > 0 ? site.Signature.TypeParameters[0] : site.ElementType;
        var call = site.Operator switch
        {
            OperatorKind.Skip or OperatorKind.Take => $"{SqlProjection}.{site.Operator}(query, {parameters[1].Name})",
            _ when site.Aggregate is { } aggregate => Aggregate(
                SqlProjection,
                site,
                site.Signature.TypeParameters.Count > 0 ? element : site.ElementType,
                "query",
                propertyPath: null,
                aggregate),
            _ when site.IsAsync => $"{SqlProjection}.{site.Operator}{AsyncSuffix}(query, {parameters[parameters.Count - 1].Name})",
            _ => $"{SqlProjection}.{site.Operator}(query)",
        };

        // Enumerable.ToList and ToArray accept any sequence; every other operator is on a query already.
        var test = site.Signature.ContainingType == Enumerable
            ? $"{source} is {Queryable}<{element}> query && {SqlProjection}.IsInterceptable(query)"
            : $"{source} is var query && {SqlProjection}.IsInterceptable(query)";
        writer
            .Open($"if ({test})")
            .Line($"return {call};")
            .Close()
            .Line()
            .Line($"return {fallback};")
            .Close();
    }

    // The group values a call passes: a result selector's, or the call's own.
    private static EquatableArray<string> GroupValues(GroupCallModel call)
        => call.Kind == GroupCallKind.GroupBy ? call.GroupBy?.Result?.Values ?? default : call.Values;

    // GroupBy, and the operators on its groups and after a Select of them. The interceptors are generic: the key, and
    // so the grouping type, can be anonymous.
    private static void WriteGroup(CodeWriter writer, CallSite site, GroupCallModel group, string source, string fallback, string template, string values)
    {
        var signature = site.Signature!;
        var typeParameters = signature.TypeParameters;
        var slots = Slots(group.PredicateValues);
        var guard = $"if (!{SqlGrouping}.IsInterceptable({source}))";
        switch (group.Kind)
        {
            case GroupCallKind.GroupBy:
                WriteGroupBy(writer, group.GroupBy!, source, fallback, values, typeParameters);
                return;

            case GroupCallKind.ProjectedWhere or GroupCallKind.ProjectedOrder:
                writer.Open($"if ({source} is var query && {SqlProjection}.IsInterceptable(query))");
                WriteCaptures(writer, group.CaptureCount, group.CaptureParameter);
                writer
                    .Line(group.Kind == GroupCallKind.ProjectedWhere
                        ? $"return {SqlProjection}.Where(query, {template}, {values}, {slots});"
                        : $"return {SqlProjection}.{site.Operator}(query, {values}[0], {slots});")
                    .Close()
                    .Line()
                    .Line($"return {fallback};")
                    .Close();
                return;

            case GroupCallKind.Terminal or GroupCallKind.Where when site.Operator is OperatorKind.ToList or OperatorKind.ToArray && signature.ContainingType == Enumerable:
                // Enumerable.ToList and ToArray accept any sequence; only grouped KetPsi queries run here.
                writer
                    .Open($"if ({source} is {Queryable}<{typeParameters[0]}> query && {SqlGrouping}.IsInterceptable(query))")
                    .Line($"return {SqlGrouping}.{site.Operator}(query);")
                    .Close()
                    .Line()
                    .Line($"return {fallback};")
                    .Close();
                return;
        }

        writer
            .Open(guard)
            .Line($"return {fallback};")
            .Close()
            .Line();
        WriteCaptures(writer, group.CaptureCount, group.CaptureParameter);

        var call = group.Kind switch
        {
            GroupCallKind.Where when site.Operator == OperatorKind.Where => $"{SqlGrouping}.Where({source}, {template}, {values}, {slots})",
            GroupCallKind.Order => $"{SqlGrouping}.{site.Operator}({source}, {values}[0], {slots})",
            GroupCallKind.Select =>
                $"({Queryable}<{typeParameters[typeParameters.Count - 1]}>)(object){SqlGrouping}.Select({source}, {values}, {slots}, {ReaderHelper}({group.ReaderCode}))",
            _ => Terminal(site, group.Kind == GroupCallKind.Where ? $"{SqlGrouping}.Where({source}, {template}, {values}, {slots})" : source),
        };
        writer.Line($"return {call};").Close();
    }

    private static string Terminal(CallSite site, string query)
    {
        var parameters = site.Signature!.Parameters;
        return site.IsAsync
            ? $"{SqlGrouping}.{site.Operator}{AsyncSuffix}({query}, {parameters[parameters.Count - 1].Name})"
            : $"{SqlGrouping}.{site.Operator}({query})";
    }

    private static void WriteGroupBy(
        CodeWriter writer, GroupByModel groupBy, string source, string fallback, string values, EquatableArray<string> typeParameters)
    {
        var entity = groupBy.EntityType;
        var key = typeParameters[1];
        var element = typeParameters.Contains("TElement") ? "TElement" : typeParameters[0];
        writer
            .Line($"var query = ({Queryable}<{entity}>)(object){source};")
            .Open($"if (!{SqlQuery}.IsInterceptable(query))")
            .Line($"return {fallback};")
            .Close()
            .Line();

        // A result selector returns its own results, never the groups, so it reads no element.
        var result = groupBy.Result;
        string elementPaths, elementEntityPaths, elementReader;
        if (result is null)
        {
            WriteCaptures(writer, groupBy.ElementCaptureCount, groupBy.ElementParameter);
            (elementPaths, elementEntityPaths) = (Strings(groupBy.ElementPaths), Strings(groupBy.ElementEntityPaths));
            elementReader = $"({ProjectionReader}<{element}>)(object){ReaderHelper}({groupBy.ElementReaderCode})";
        }
        else
        {
            (elementPaths, elementEntityPaths) = (Strings(default), Strings(default));
            elementReader = $"({ProjectionReader}<{element}>)(static ({ProjectionTranslator.Reader}, {ProjectionTranslator.Ordinals}, {ProjectionTranslator.Entities}) => default!)";
        }

        writer
            .Line($"var groups = {SqlGrouping}.GroupBy<{entity}, {key}, {element}>(")
            .Line("    query,")
            .Line($"    {Strings(groupBy.KeyPaths)},")
            .Line($"    ({ProjectionReader}<{key}>)(object){ReaderHelper}({groupBy.KeyReaderCode}),")
            .Line($"    {elementPaths},")
            .Line($"    {elementEntityPaths},")
            .Line($"    {elementReader});");

        if (result is null)
        {
            writer.Line("return groups;").Close();
            return;
        }

        WriteCaptures(writer, result.CaptureCount, result.CaptureParameter);
        writer
            .Line($"return ({Queryable}<{typeParameters[typeParameters.Count - 1]}>)(object){SqlGrouping}.Select(groups, {values}, {Slots(result.PredicateValues)}, {ReaderHelper}({result.ReaderCode}));")
            .Close();
    }

    // Captured values are read once per call, in source order, from the lambda the caller built.
    private static void WriteCaptures(CodeWriter writer, int count, string? parameter)
    {
        if (count > 0 && parameter is not null)
        {
            writer.Line($"var {ProjectionTranslator.Captures} = {CapturedValues}.ReadAll({parameter});");
        }
    }

    private static string Slots(EquatableArray<string> values)
        => values.Count == 0 ? NoValues : $"new object?[] {{ {string.Join(", ", values)} }}";

    // SqlQuery.Aggregate over an entity property, or SqlProjection.Aggregate over a one-column projection.
    private static string Aggregate(string type, CallSite site, string element, string source, string? propertyPath, AggregateModel aggregate)
    {
        var parameters = site.Signature!.Parameters;
        var arguments = new List<string> { source, $"{AggregateFunction}.{site.Operator}" };
        if (propertyPath is not null)
        {
            arguments.Add($"\"{propertyPath}\"");
        }

        arguments.Add($"{AggregateValueType}.{aggregate.ValueType}");
        if (site.IsAsync)
        {
            arguments.Add(parameters[parameters.Count - 1].Name);
        }

        var method = site.IsAsync ? "AggregateAsync" : "Aggregate";
        return $"{type}.{method}<{element}, {aggregate.ResultType}>({string.Join(", ", arguments)})";
    }

    private static bool IsAggregate(OperatorKind kind)
        => kind is OperatorKind.Sum or OperatorKind.Average or OperatorKind.Min or OperatorKind.Max;

    private static string Strings(EquatableArray<string> values)
        => values.Count == 0
            ? "global::System.Array.Empty<string>()"
            : "new string[] { " + string.Join(", ", values.Select(static v => "\"" + v + "\"")) + " }";

    private static string Body(CallSite site, string source, string template)
    {
        var parameters = site.Signature!.Parameters;
        var values = site.Predicate is null ? NoValues : Values(site.Predicate);
        switch (site.Operator)
        {
            case OperatorKind.Where:
                return $"{SqlQuery}.Where({source}, {template}, {values})";
            case OperatorKind.WhereIf:
                // The condition usually guards the values, so they are only read when it holds.
                var condition = parameters[1].Name;
                return $"{SqlQuery}.WhereIf({source}, {condition}, {template}, {condition} ? {values} : {NoValues})";
            case OperatorKind.OrderBy or OperatorKind.OrderByDescending or OperatorKind.ThenBy or OperatorKind.ThenByDescending:
                return $"{SqlQuery}.{site.Operator}({source}, \"{site.OrderProperty}\")";
            case OperatorKind.Skip or OperatorKind.Take:
                return $"{SqlQuery}.{site.Operator}({source}, {parameters[1].Name})";
            case OperatorKind.AsNoTracking or OperatorKind.AsNoTrackingWithIdentityResolution:
                return $"{SqlQuery}.{site.Operator}({source})";
            case OperatorKind.Include or OperatorKind.ThenInclude:
                var include = site.Include!;
                return $"{SqlQuery}.{site.Operator}<{site.ElementType}, {include.PropertyTypeName}>({source}, \"{include.Navigation}\")";
            case OperatorKind.Distinct:
                return $"{SqlQuery}.Distinct({source})";
            case OperatorKind.Sum or OperatorKind.Average or OperatorKind.Min or OperatorKind.Max:
                return Aggregate(SqlQuery, site, site.ElementType, source, site.Aggregate!.PropertyPath, site.Aggregate);
            case OperatorKind.AsSplitQuery or OperatorKind.AsSingleQuery:
                // KetPsi always loads included collections with their own statements; both give the same results.
                return source;
            case OperatorKind.AsTracking:
                return parameters.Count > 1
                    ? $"{SqlQuery}.AsTracking({source}, {parameters[1].Name})"
                    : $"{SqlQuery}.AsTracking({source})";
            case OperatorKind.IgnoreQueryFilters:
                return parameters.Count > 1
                    ? $"{SqlQuery}.IgnoreQueryFilters({source}, {parameters[1].Name})"
                    : $"{SqlQuery}.IgnoreQueryFilters({source})";
            default:
                // Terminals; a predicate becomes a Where before the terminal.
                var query = site.HasPredicate ? $"{SqlQuery}.Where({source}, {template}, {values})" : source;
                return site.IsAsync
                    ? $"{SqlQuery}.{site.Operator}{AsyncSuffix}({query}, {parameters[parameters.Count - 1].Name})"
                    : $"{SqlQuery}.{site.Operator}({query})";
        }
    }

    private static string Values(PredicateModel predicate)
    {
        if (predicate.ValuePaths.Count == 0)
        {
            return NoValues;
        }

        var reads = predicate.ValuePaths.Select(static path => $"{CapturedValues}.Read({path})");
        return $"new object?[] {{ {string.Join(", ", reads)} }}";
    }

    private static bool TakesPredicate(CallSite site)
        => site.HasPredicate || site.Operator is OperatorKind.Where or OperatorKind.WhereIf;

    private static bool IsOrdering(OperatorKind kind)
        => kind is OperatorKind.OrderBy or OperatorKind.OrderByDescending or OperatorKind.ThenBy or OperatorKind.ThenByDescending;
}
