using System.Globalization;
using KetPsi.EntityFrameworkCore.Generator.Discovery;
using KetPsi.EntityFrameworkCore.Generator.Model;

namespace KetPsi.EntityFrameworkCore.Generator.Emit;

/// <summary>
/// Emits one reader per entity, one navigation accessor per navigation of an included entity, and the module
/// initializer that registers them, together with the SQL dialect.
/// </summary>
internal static class ReaderEmitter
{
    public const string HintName = "KetPsi.EntityReaders.g.cs";

    private const string Infrastructure = "global::KetPsi.EntityFrameworkCore.Infrastructure";
    private const string CompilerServices = "global::System.Runtime.CompilerServices";
    private const string SqlServerDialect = "global::KetPsi.EntityFrameworkCore.SqlServer.SqlServerDialect";
    private const string Reader = "reader";
    private const string Ordinals = "ordinals";
    private const string Entity = "entity";

    public static string Emit(IReadOnlyList<EntityShape> entities, bool registerSqlServer, IReadOnlyList<EntityShape>? navigationEntities = null)
    {
        navigationEntities ??= [];
        var writer = new CodeWriter()
            .Line("// <auto-generated/>")
            .Line("#nullable enable")
            .Line()
            .Open("namespace " + QueryInterceptorGenerator.GeneratedNamespace);

        WriteRegistration(writer, entities, registerSqlServer, navigationEntities);
        foreach (var entity in entities)
        {
            writer.Line();
            WriteReader(writer, entity);
        }

        foreach (var entity in navigationEntities)
        {
            foreach (var navigation in entity.Navigations)
            {
                writer.Line();
                WriteNavigationAccessor(writer, entity, navigation);
            }
        }

        return writer.Close().ToString();
    }

    private static void WriteRegistration(
        CodeWriter writer, IReadOnlyList<EntityShape> entities, bool registerSqlServer, IReadOnlyList<EntityShape> navigationEntities)
    {
        writer
            .Line("[global::System.CodeDom.Compiler.GeneratedCode(\"KetPsi.EntityFrameworkCore.Generator\", null)]")
            .Open("internal static class KetPsiRegistration")
            .Line($"[{CompilerServices}.ModuleInitializer]")
            .Open("internal static void Initialize()");

        if (registerSqlServer)
        {
            writer.Line($"{Infrastructure}.SqlDialects.Register({SqlServerDialect}.Instance);");
        }

        foreach (var entity in entities)
        {
            writer.Line($"{Infrastructure}.EntityReaders.Register(new {entity.ReaderName}());");
        }

        foreach (var entity in navigationEntities)
        {
            foreach (var navigation in entity.Navigations)
            {
                writer.Line($"{Infrastructure}.EntityNavigations.Register(new {AccessorName(entity, navigation)}());");
            }
        }

        writer.Close().Close();
    }

    private static void WriteNavigationAccessor(CodeWriter writer, EntityShape entity, NavigationShape navigation)
    {
        var target = "target";
        var property = $"{entity.TypeName.Replace("global::", "")}.{navigation.Name}";
        writer
            .Open($"file sealed class {AccessorName(entity, navigation)} : {Infrastructure}.INavigationAccessor")
            .Line($"public global::System.Type EntityType => typeof({entity.TypeName});")
            .Line()
            .Line($"public string NavigationName => \"{navigation.Name}\";")
            .Line()
            .Open($"public void SetReference(object {Entity}, object? value)");
        if (!navigation.IsCollection && navigation.Setter is { } setter)
        {
            writer.Line(SetValue(navigation, setter, $"(({entity.TypeName}){Entity})", $"({navigation.TypeName})value!") + ";");
        }
        else
        {
            writer.Line($"throw new global::System.NotSupportedException(\"{property} cannot be set.\");");
        }

        writer.Close().Line().Open($"public void EnsureCollection(object {Entity})");
        if (navigation.IsCollection)
        {
            writer
                .Line($"var {target} = ({entity.TypeName}){Entity};")
                .Open($"if ({GetValue(navigation, target)} is null)");
            if (navigation.CreateTypeName is { } create && navigation.Setter is { } collectionSetter)
            {
                writer.Line(SetValue(navigation, collectionSetter, target, $"new {create}()") + ";");
            }
            else
            {
                writer.Line($"throw new global::System.InvalidOperationException(\"{property} is null and cannot be created; initialize the collection in the entity.\");");
            }

            writer.Close();
        }
        else
        {
            writer.Line($"throw new global::System.NotSupportedException(\"{property} is not a collection.\");");
        }

        writer.Close().Line().Open($"public void AddToCollection(object {Entity}, object item)");
        if (navigation.IsCollection)
        {
            writer
                .Line($"EnsureCollection({Entity});")
                .Line($"((global::System.Collections.Generic.ICollection<{navigation.ElementTypeName}>){GetValue(navigation, $"(({entity.TypeName}){Entity})")}!).Add(({navigation.ElementTypeName})item);");
        }
        else
        {
            writer.Line($"throw new global::System.NotSupportedException(\"{property} is not a collection.\");");
        }

        writer.Close();

        if (navigation.Getter == Setter.Accessor)
        {
            writer
                .Line()
                .Line($"[{CompilerServices}.UnsafeAccessor({CompilerServices}.UnsafeAccessorKind.Method, Name = \"get_{navigation.Name}\")]")
                .Line($"private static extern {navigation.TypeName} Get{navigation.Name}({navigation.DeclaringTypeName} {Entity});");
        }

        if (navigation.Setter == Setter.Accessor)
        {
            writer
                .Line()
                .Line($"[{CompilerServices}.UnsafeAccessor({CompilerServices}.UnsafeAccessorKind.Method, Name = \"set_{navigation.Name}\")]")
                .Line($"private static extern void Set{navigation.Name}({navigation.DeclaringTypeName} {Entity}, {navigation.TypeName} value);");
        }

        writer.Close();
    }

    private static string GetValue(NavigationShape navigation, string target)
        => navigation.Getter == Setter.Accessor ? $"Get{navigation.Name}({target})" : $"{target}.{navigation.Name}";

    private static string SetValue(NavigationShape navigation, Setter setter, string target, string value)
        => setter == Setter.Accessor ? $"Set{navigation.Name}({target}, {value})" : $"{target}.{navigation.Name} = {value}";

    private static string AccessorName(EntityShape entity, NavigationShape navigation)
        => EntityShapeBuilder.ReaderName(entity.TypeName).Replace("_Reader", "") + "_" + navigation.Name + "_Navigation";

    private static void WriteReader(CodeWriter writer, EntityShape entity)
    {
        var properties = entity.Properties;

        writer
            .Open($"file sealed class {entity.ReaderName} : {Infrastructure}.IEntityReader<{entity.TypeName}>")
            .Line("private static readonly string[] Names =")
            .Line("[");
        foreach (var property in properties)
        {
            writer.Line($"    \"{property.Name}\",");
        }

        writer
            .Line("];")
            .Line()
            .Line("public global::System.Collections.Generic.IReadOnlyList<string> PropertyNames => Names;")
            .Line()
            .Open($"public {entity.TypeName} Read(global::System.Data.Common.DbDataReader {Reader}, global::System.ReadOnlySpan<int> {Ordinals})");

        WriteConstruction(writer, entity);
        for (var i = 0; i < properties.Count; i++)
        {
            var property = properties[i];
            switch (property.Setter)
            {
                case Setter.Direct:
                    writer.Open($"if ({Ordinal(i)} >= 0)").Line($"{Entity}.{property.Name} = {ReadValue(property, i)};").Close();
                    break;
                case Setter.Accessor:
                    writer.Open($"if ({Ordinal(i)} >= 0)").Line($"{SetterName(property)}({Entity}, {ReadValue(property, i)});").Close();
                    break;
            }
        }

        writer.Line($"return {Entity};").Close();
        WriteAccessors(writer, entity);
        writer.Close();
    }

    private static void WriteConstruction(CodeWriter writer, EntityShape entity)
    {
        if (entity.Construction == Construction.Accessor)
        {
            writer.Line($"var {Entity} = CreateEntity();");
            return;
        }

        var initProperties = entity.Properties.Select((p, i) => (Property: p, Index: i)).Where(static p => p.Property.Setter == Setter.Init).ToList();
        if (initProperties.Count == 0)
        {
            writer.Line($"var {Entity} = new {entity.TypeName}();");
            return;
        }

        // Init-only properties can only be set here; an unmapped one gets its type's default.
        writer.Line($"var {Entity} = new {entity.TypeName}").Line("{");
        foreach (var (property, index) in initProperties)
        {
            writer.Line($"    {property.Name} = {Ordinal(index)} >= 0 ? ({ReadValue(property, index)}) : default!,");
        }

        writer.Line("};");
    }

    private static void WriteAccessors(CodeWriter writer, EntityShape entity)
    {
        if (entity.Construction == Construction.Accessor)
        {
            writer
                .Line()
                .Line($"[{CompilerServices}.UnsafeAccessor({CompilerServices}.UnsafeAccessorKind.Constructor)]")
                .Line($"private static extern {entity.TypeName} CreateEntity();");
        }

        foreach (var property in entity.Properties.Where(static p => p.Setter == Setter.Accessor))
        {
            writer
                .Line()
                .Line($"[{CompilerServices}.UnsafeAccessor({CompilerServices}.UnsafeAccessorKind.Method, Name = \"set_{property.Name}\")]")
                .Line($"private static extern void {SetterName(property)}({property.DeclaringTypeName} {Entity}, {property.TypeName} value);");
        }
    }

    private static string ReadValue(PropertyShape property, int index)
    {
        var ordinal = Ordinal(index);
        var call = property.Read == ReadMethod.GetFieldValue
            ? $"{Reader}.GetFieldValue<{property.ValueTypeName}>({ordinal})"
            : $"{Reader}.{property.Read}({ordinal})";

        // Enums are read as their underlying number.
        if (property.Read != ReadMethod.GetFieldValue && property.ValueTypeName is not null)
        {
            call = $"({UnderlyingPropertyType(property)}){call}";
        }

        if (!property.CanBeNull)
        {
            return call;
        }

        // A non-nullable reference property can still hold a database null, as it does in EF Core.
        var nullValue = IsNullableValueType(property) ? "null" : "null!";
        return $"{Reader}.IsDBNull({ordinal}) ? {nullValue} : {call}";
    }

    private static bool IsNullableValueType(PropertyShape property)
        => property.TypeName.EndsWith("?", StringComparison.Ordinal);

    // The non-nullable property type, which an enum value is cast to.
    private static string UnderlyingPropertyType(PropertyShape property)
        => IsNullableValueType(property) ? property.TypeName.Substring(0, property.TypeName.Length - 1) : property.TypeName;

    private static string Ordinal(int index) => $"{Ordinals}[{index.ToString(CultureInfo.InvariantCulture)}]";

    private static string SetterName(PropertyShape property) => "Set" + property.Name;
}
