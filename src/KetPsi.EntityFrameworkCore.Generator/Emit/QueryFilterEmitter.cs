using System.Globalization;
using KetPsi.EntityFrameworkCore.Generator.Discovery;
using KetPsi.EntityFrameworkCore.Generator.Model;
using Microsoft.CodeAnalysis.CSharp;

namespace KetPsi.EntityFrameworkCore.Generator.Emit;

/// <summary>Emits the registration of every translated query filter, with the code that reads its values from the context.</summary>
internal static class QueryFilterEmitter
{
    public const string HintName = "KetPsi.QueryFilters.g.cs";

    private const string QueryFilters = "global::KetPsi.EntityFrameworkCore.Infrastructure.QueryFilters";
    private const string PredicateTemplate = "global::KetPsi.EntityFrameworkCore.Infrastructure.Templates.PredicateTemplate";
    private const string CompilerServices = "global::System.Runtime.CompilerServices";
    private const string NoValues = "global::System.Array.Empty<object?>()";

    public static string Emit(IReadOnlyList<QueryFilterModel> filters)
    {
        var writer = new CodeWriter()
            .Line("// <auto-generated/>")
            .Line("#nullable enable")
            .Line()
            .Open("namespace " + QueryInterceptorGenerator.GeneratedNamespace)
            .Line("[global::System.CodeDom.Compiler.GeneratedCode(\"KetPsi.EntityFrameworkCore.Generator\", null)]")
            .Open("internal static class KetPsiQueryFilterRegistration");

        for (var i = 0; i < filters.Count; i++)
        {
            writer.Line($"private static readonly {PredicateTemplate} {Template(i)} = {filters[i].TemplateCode};");
        }

        writer
            .Line()
            .Line($"[{CompilerServices}.ModuleInitializer]")
            .Open("internal static void Initialize()");

        for (var i = 0; i < filters.Count; i++)
        {
            var filter = filters[i];
            var key = filter.FilterKey is null ? "null" : SymbolDisplay.FormatLiteral(filter.FilterKey, quote: true);
            writer.Line(
                $"{QueryFilters}.Register(typeof({filter.ContextType}), typeof({filter.EntityType}), {key}, {Template(i)}, {ValueReader(filter, i)});");
        }

        writer.Close();

        for (var i = 0; i < filters.Count; i++)
        {
            foreach (var accessor in filters[i].Accessors)
            {
                WriteAccessor(writer, accessor, Prefix(i));
            }
        }

        return writer.Close().Close().ToString();
    }

    private static string ValueReader(QueryFilterModel filter, int index)
    {
        var parameter = ContextValueReader.ContextParameter;
        if (filter.ValueCodes.Count == 0)
        {
            return $"static {parameter} => {NoValues}";
        }

        var values = filter.ValueCodes.Select(code => code.Replace(ContextValueReader.AccessorPrefix, Prefix(index)));
        return $"static {parameter} => new object?[] {{ {string.Join(", ", values)} }}";
    }

    private static void WriteAccessor(CodeWriter writer, AccessorModel accessor, string prefix)
    {
        var name = accessor.Name.Replace(ContextValueReader.AccessorPrefix, prefix);
        writer.Line();
        if (accessor.IsField)
        {
            writer
                .Line($"[{CompilerServices}.UnsafeAccessor({CompilerServices}.UnsafeAccessorKind.Field, Name = \"{accessor.MemberName}\")]")
                .Line($"private static extern ref {accessor.ValueType} {name}({accessor.DeclaringType} context);");
        }
        else
        {
            writer
                .Line($"[{CompilerServices}.UnsafeAccessor({CompilerServices}.UnsafeAccessorKind.Method, Name = \"get_{accessor.MemberName}\")]")
                .Line($"private static extern {accessor.ValueType} {name}({accessor.DeclaringType} context);");
        }
    }

    private static string Template(int index) => "Filter" + index.ToString(CultureInfo.InvariantCulture);

    private static string Prefix(int index) => Template(index);
}
